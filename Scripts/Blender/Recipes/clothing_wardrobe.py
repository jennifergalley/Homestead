def load_inputs():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    arm, meshes = B.import_skeletal(BODY_FBX)
    arm.name = "root"
    body_obj = meshes[0]
    body_obj.name = "SKM_MHC_Heroine_BodyMesh"
    face_arm, face_meshes = B.import_skeletal(FACE_FBX)
    face_arm.name = "FaceRig"
    face_obj = face_meshes[0]
    face_obj.name = "SKM_MHC_Heroine_FaceMesh"
    body = B.Body(arm, body_obj, extra=[face_obj])
    base = {}
    for path, name in ((SHORTS_FBX, "SKM_PrimitiveShorts"), (TANK_FBX, "SKM_PrimitiveTankTop")):
        a2, ms = B.import_skeletal(path)
        obj = ms[0]
        obj.name = name
        mw = obj.matrix_world.copy()
        obj.parent = arm
        obj.matrix_world = mw
        for mod in obj.modifiers:
            if mod.type == "ARMATURE":
                mod.object = arm
        ad = a2.data
        bpy.data.objects.remove(a2)
        bpy.data.armatures.remove(ad)
        base[name] = obj
    belt = Tp.Belt(json.loads(BELT_JSON.read_text()))
    return arm, body_obj, face_obj, body, base, belt


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", default="all", choices=["fit", "build", "render", "all"])
    ap.add_argument("--samples", type=int, default=192)
    ap.add_argument("--reuse-textures", action="store_true")
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--garments", nargs="*", help="fit stage: tee longshirt coat (trousers always)")
    args = ap.parse_args(argv)
    if args.stage == "render":
        render_stage(args)
        return
    np.random.seed(SEED)
    WORK.mkdir(parents=True, exist_ok=True)
    arm, body_obj, face_obj, body, base, belt = load_inputs()
    log("landmarks " + json.dumps({k: (np.round(v, 4).tolist() if isinstance(v, list) else round(v, 4))
                                  for k, v in body.lm.items()}))
    fitted = fit_all(body, belt, base["SKM_PrimitiveShorts"], args.garments)
    objs = {}
    for name, (g, V, F) in fitted.items():
        obj, F2 = garment_object(g, V, F, body)
        fitted[name] = (g, V, F2)
        objs[name] = obj
    if args.stage == "fit":
        for name in objs:
            if name == "SKM_WoolTrousers":
                preview({name}, WORK / f"fit_{name}.png",
                        views=(("front", (0, -4, 0.6), (90, 0, 0)), ("side", (4, 0, 0.6), (90, 0, 90)),
                               ("back", (0, 4, 0.6), (90, 0, 180))), scale=1.25)
            else:
                preview({name}, WORK / f"fit_{name}.png")
        if "SKM_FurCoat" in objs:
            preview({"SKM_WoolTrousers", "SKM_LinenLongShirt", "SKM_FurCoat"}, WORK / "fit_layered.png")
        if "SKM_LinenLongShirt" in objs:
            preview({"SKM_LinenLongShirt"}, WORK / "zoom_ls.png",
                    views=(("waist", (4, 0, 1.15), (90, 0, 90)), ("arm", (0.22, -4, 1.25), (90, 0, 0)),
                           ("neck", (0.0, -4, 1.42), (90, 0, 0))), scale=0.45)
        bpy.ops.wm.save_as_mainfile(filepath=str(WORK / "fit.blend"))
        return
    build(args, arm, body_obj, face_obj, body, base, fitted, objs)
    if args.stage == "all":
        render_stage(args)


