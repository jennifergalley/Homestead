def vertex_normals(V, F):
    N = np.zeros_like(V)
    for k in range(4):
        a, b, c = F[:, k], F[:, (k + 1) % 4], F[:, (k + 3) % 4]
        N_ = np.cross(V[b] - V[a], V[c] - V[a])
        np.add.at(N, a, N_)
    return N / np.maximum(np.linalg.norm(N, axis=1, keepdims=True), 1e-12)


def orient_out(V, F, body_surf):
    """Make the quad winding consistent across the whole garment (topologically, so faces on the
    inside of a sleeve next to the torso can't be misjudged), then flip everything if most faces
    point into the body."""
    import bmesh
    bm = bmesh.new()
    vs = [bm.verts.new(v) for v in V]
    for f in F:
        bm.faces.new([vs[i] for i in f])
    bm.faces.ensure_lookup_table()
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    F2 = np.array([[v.index for v in f.verts] for f in bm.faces], np.int64)
    bm.free()
    cent = V[F2].mean(1)
    fn = np.cross(V[F2[:, 1]] - V[F2[:, 0]], V[F2[:, 3]] - V[F2[:, 0]])
    _, _, bn = body_surf.signed(cent)
    if ((fn * bn).sum(1) > 0).mean() < 0.5:
        F2 = F2[:, ::-1].copy()
    return F2


def shell_layer(V, F, thick, name):
    """Approximate outer shell (fitted surface pushed out by the cloth thickness) as a layer."""
    N = vertex_normals(V, F)
    Vo = V + N * np.broadcast_to(thick, (len(V),))[:, None]
    T = np.concatenate([F[:, [0, 1, 2]], F[:, [0, 2, 3]]])
    return Ly.LayerSurface(Vo, N, T, name)


def mesh_layer(obj, body_surf):
    return Ly.outer_shell(obj, body_surf)


class Wrapped:
    """MultiSurface -> the 4-tuple constraint interface."""

    def __init__(self, ms):
        self.ms = ms

    def signed(self, pts):
        s, loc, nrm = self.ms.signed(pts)
        return s, loc, nrm, np.ones(len(pts), bool)


class MultiSurface:
    def __init__(self, surfs, labels):
        self.surfs, self.labels = surfs, labels

    def signed(self, pts, idx=None):
        lab = self.labels if idx is None else self.labels[idx]
        s = np.empty(len(pts)); loc = np.empty_like(pts); nrm = np.empty_like(pts)
        for i, surf in enumerate(self.surfs):
            m = lab == i
            if m.any():
                s[m], loc[m], nrm[m] = surf.signed(pts[m])
        return s, loc, nrm


class Labelled:
    """Per-vertex surface choice for the relax (which passes all vertices in order)."""

    def __init__(self, surfs, labels):
        self.ms = MultiSurface(surfs, labels)

    def signed(self, pts):
        s, loc, nrm = self.ms.signed(pts)
        return s, loc, nrm, np.ones(len(pts), bool)


