def show_only(names):
    for n in ALL_GARMENTS:
        o = bpy.data.objects.get(n)
        if o:
            o.hide_render = n not in names


def render_stage(args):
    bpy.ops.wm.open_mainfile(filepath=str(BLEND))
    RENDERS.mkdir(parents=True, exist_ok=True)
    backend = Rn.setup_scene(HDRI, args.samples)
    log(f"render device {backend}")
    arm = bpy.data.objects["root"]
    body_obj = bpy.data.objects["SKM_MHC_Heroine_BodyMesh"]
    face = bpy.data.objects["SKM_MHC_Heroine_FaceMesh"]
    want = set(args.only or [])
    R.reset_pose(arm)
    for name, (vis, tgt, d, dist, lens, res, fstop) in REVIEW.items():
        if want and name not in want:
            continue
        show_only(vis)
        Rn.shoot(RENDERS / f"{name}.png", tgt, d, dist, lens, res, fstop)
        log(f"rendered {name}")
    for outfit, vis in POSE_OUTFITS.items():
        for pose in WR.POSES:
            tag = f"pose_{outfit}_{pose}"
            if want and tag not in want and pose not in want:
                continue
            show_only(vis)
            WR.apply_pose(arm, pose)
            objs = [body_obj, face] + [bpy.data.objects[n] for n in vis]
            R.ground(arm, objs)
            V = np.vstack([B.mesh_arrays(o)[0] for o in [body_obj, face]])
            lo, hi = V.min(0), V.max(0)
            c = (lo + hi) / 2
            size = float(np.max(hi - lo))
            Rn.shoot(RENDERS / f"{tag}.png", tuple(c), (-0.8, -1, 0.18), 1.55 * size + 1.2, 55, (2160, 3840), None)
            log(f"rendered {tag}")
    R.reset_pose(arm)


