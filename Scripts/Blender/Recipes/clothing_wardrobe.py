def collide_constraints(g, V, body, layers):
    kind = g.extra["params"]["kind"]
    if kind == "trousers":
        lab = g.extra["labels"]
        off = np.maximum(0.0030, 0.85 * g.extra["offsets"])
        return [(Labelled([body.torso, body.leg_l, body.leg_r], lab), off, None),
                (Tr.Plane(1.0, 0.0018), np.zeros(len(V)), lab == 1),
                (Tr.Plane(-1.0, 0.0018), np.zeros(len(V)), lab == 2)]
    off = np.maximum(0.0028 if kind != "coat" else 0.009, 0.6 * g.extra["offsets"])
    cons = [(Ly.ClosedSurface(body.all), off, None)]
    low = V[:, 2] < 1.16
    for lay, loff in layers:
        cons.append((lay, np.full(len(V), loff), low if kind != "coat" else None))
    return cons


def detail(g, V, F, obj, body, layers):
    polys, _ = WD.edge_polylines(g, V, F)
    for k, lst in g.features.items():
        polys.setdefault(k, []).extend(lst)
    fields = WD.fields_for(V, polys)
    h = WD.wrinkles(g, V, fields, body, SEED)
    _, _, n = body.all.signed(V)
    V2 = Ly.collide_layers(V + n * h[:, None], collide_constraints(g, V, body, layers), rounds=2)
    set_verts(obj, V2)
    fields = WD.fields_for(V2, polys)
    gap = body.all.signed(V2)[0]
    log(f"{g.name}: wrinkles {1000 * np.abs(h).max():.1f} mm max, skin gap mm min {1000 * gap.min():.2f} "
        f"median {1000 * np.median(gap):.2f}")
    return V2, fields, gap


def limb_blend(g, V):
    kind = g.extra["params"]["kind"]
    if kind == "trousers":
        lab = g.extra["labels"]
        w = D._smooth(g.extra["params"]["junction_z"] - V[:, 2], 0.02, 0.08)
        return {("leg", "l"): w * (lab == 1), ("leg", "r"): w * (lab == 2)}
    reg, ax = g.extra["region"], g.extra["axial"]
    w = D._smooth(ax, 0.03, 0.10)
    return {("arm", "l"): w * (reg == 1), ("arm", "r"): w * (reg == 2)}


def edge_group(obj, edge, name="_edge"):
    vg = obj.vertex_groups.new(name=name)
    for i, d in enumerate(edge):
        vg.add([i], float(np.clip(d / 0.05, 0, 1)), "REPLACE")


def read_group(obj, name, scale=1.0):
    eg = obj.vertex_groups[name]
    e = np.zeros(len(obj.data.vertices))
    for v in obj.data.vertices:
        for gg in v.groups:
            if gg.group == eg.index:
                e[v.index] = gg.weight * scale
    obj.vertex_groups.remove(eg)
    return e


def join_parts(obj, parts, src):
    for p in parts:
        R.transfer_weights(p, src)
        pn, pw = R.read_weights(p)
        R.write_weights(p, pn, R.clean_weights(pw))
        p.data.materials.append(obj.data.materials[0])
    bpy.ops.object.select_all(action="DESELECT")
    for p in parts:
        p.select_set(True)
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    if parts:
        bpy.ops.object.join()


def attach(obj, arm):
    mod = obj.modifiers.new("Armature", "ARMATURE")
    mod.object = arm
    obj.parent = arm


def build_cloth(name, g, V, F, obj, body, layers, src, limb, arm, rng):
    kind = g.extra["params"]["kind"]
    short = name.replace("SKM_", "")
    V, fields, gap = detail(g, V, F, obj, body, layers)
    uvpm = D.unwrap(obj)
    tdir = gdir(name) / "Textures"
    tdir.mkdir(parents=True, exist_ok=True)
    extra, eye = {}, None
    if kind == "longshirt":
        sV, sN, sT = B.mesh_arrays(obj, evaluated=False)
        eye = WR.eyelets(g, V, B.Surface(sV, sN, sT))
        extra["eyelets"] = np.array(eye["l"] + eye["r"])
    if kind == "trousers" and g.extra["params"].get("knee_patch", True):
        kn = body.bones["calf_l"][0]
        target = np.array([kn[0], kn[1] - 0.07, kn[2] + 0.02])
        c = V[np.argmin(np.linalg.norm(V - target, axis=1))]
        extra["patch"] = (c, (0.046, 0.037), 0.0)
    cached = WORK / f"tex_{short}.json"
    if REUSE["tex"] and cached.exists():
        prev = json.loads(cached.read_text())
        paths = {k: Path(v) for k, v in prev["paths"].items()}
        stats = prev["stats"]
        log(f"{name}: reusing textures")
    else:
        paths, stats = WT.compose_cloth(obj, fields, uvpm, tdir, short, R_out=2048, supersample=2, seed=SEED,
                                        log=log, **extra)
        cached.write_text(json.dumps(dict(paths={k: str(v) for k, v in paths.items()}, stats=stats)))
    mat = make_material("M_" + short, paths)
    obj.data.materials.clear()
    obj.data.materials.append(mat)
    WR.skin(obj, src, limb, limb_blend(g, V), gap, edges_of(F))
    edge = np.min([fields[n][0] for n in EDGE_NAMES[kind] if n in fields], axis=0)
    edge_group(obj, edge)
    thick = 1 - D._smooth(edge, 0.004, 0.011)
    base_t, hem_t = THICKNESS[name]
    WR.make_shell(obj, base_t * (1 - thick) + hem_t * thick)
    g.extra["n_shell"] = len(obj.data.vertices)
    # loose threads: the tee's sleeve hems only (at the body hems they would hang over the cord
    # belt, at the trouser hems into the boots); the drawstring on the trousers
    pr = g.extra["params"]
    if not pr.get("threads", True):
        acc_fields = {}
    elif kind == "tee":
        acc_fields = {"hem": fields["cuff"]}
    elif kind == "trousers":
        acc_fields = {k: v for k, v in fields.items() if k != "leghem"}
    else:
        acc_fields = {}
    drawstring = kind == "trousers" and pr.get("drawstring", True)
    parts = R.accessories(obj, acc_fields, V, rng, drawstring=drawstring) if (acc_fields or drawstring) else []
    if eye is not None:
        parts += WR.lacing(obj, eye)
    join_parts(obj, parts, src)
    g.extra["edge_final"] = read_group(obj, "_edge", 0.05)
    attach(obj, arm)
    me = obj.data
    me.calc_loop_triangles()
    loft = dict(cloth_mm=round(1000 * (base_t * (1 - thick) + hem_t * thick).mean(), 2),
                air_gap_mm_median=round(1000 * float(np.median(gap)), 2), air_gap_mm_mean=round(1000 * float(np.mean(gap)), 2))
    info = dict(vertices=len(me.vertices), triangles=len(me.loop_triangles),
                bones_weighted=len(obj.vertex_groups), accessories=len(parts), texel_uv_per_m=uvpm,
                textures={k: Path(v).name for k, v in paths.items()}, texture_stats=stats, loft=loft)
    if kind == "trousers":
        below = V[:, 2] < g.extra["params"]["knee_z"] - 0.04
        outer = gap + base_t * (1 - thick) + hem_t * thick
        info["below_knee_outer_mm"] = dict(max=round(1000 * float(outer[below].max()), 2),
                                           p99=round(1000 * float(np.percentile(outer[below], 99)), 2),
                                           mean=round(1000 * float(outer[below].mean()), 2))
    log(f"{name}: built {info['vertices']} verts, {info['triangles']} tris, {info['bones_weighted']} bones, loft {loft}")
    return info


def build_coat(name, g, V, F, obj, body, layers, src, limb, arm, rng):
    p = g.extra["params"]
    short = name.replace("SKM_", "")
    V, fields, gap = detail(g, V, F, obj, body, layers)
    n0 = len(V)
    W = WR.skin(obj, src, limb, limb_blend(g, V), gap, edges_of(F), iters=6)
    del W
    reg, ax = g.extra["region"], g.extra["axial"]
    trim = np.zeros(n0)
    trim[reg == 3] = 1.0
    for side, r in (("l", 1), ("r", 2)):
        m = reg == r
        s_end = g.extra["sleeves"][side]["s_end"]
        trim[m] = np.maximum(trim[m], D._smooth(ax[m] - (s_end - p["cuff"]), -0.004, 0.006))
    if "opening" in fields:
        d_open = fields["opening"][0]
        trim = np.maximum(trim, 1 - D._smooth(d_open, p["facing"] - 0.006, p["facing"] + 0.004))
    t = THICKNESS[name][0] + (THICKNESS[name][1] - THICKNESS[name][0]) * trim
    for side in ("l", "r"):
        A = V[g.extra["sleeves"][side]["under"][0]]
        prox = np.exp(-(np.linalg.norm(V - A, axis=1) / 0.06) ** 2)
        t *= 1 - 0.6 * prox
    # the fleece packs down where the arm rests against the body: thinner down the side seams
    # and on the inside of the sleeves, so arms can come closer to the sides
    yc = np.array([body.center_y(z) for z in np.clip(V[:, 2], 0.9, 1.6)])
    th = np.degrees(np.arctan2(V[:, 0], -(V[:, 1] - yc)))
    under = np.exp(-((np.abs(th) - 90.0) / 22.0) ** 2) * D._smooth(V[:, 2], 1.06, 1.20) * (reg == 0)
    Nn = WR.smooth_normals(V, F)
    for side, r, sg in (("l", 1, 1.0), ("r", 2, -1.0)):
        m = reg == r
        under[m] = np.clip(-Nn[m, 0] * sg, 0, 1) ** 1.5
    t *= 1 - 0.45 * under
    edge = np.min([fields[n][0] for n in EDGE_NAMES["coat"] if n in fields], axis=0)
    edge_group(obj, edge)
    seams0 = {tuple(sorted(e.vertices)) for e in obj.data.edges if e.use_seam}
    N, Vo = WR.make_shell(obj, t)
    me = obj.data
    Va = np.array([v.co for v in me.vertices])
    assert len(Va) == 2 * n0, (len(Va), n0)
    inner_idx = np.arange(n0)
    outer_idx = np.arange(n0, 2 * n0)
    og = np.concatenate([inner_idx, inner_idx])
    is_outer = np.arange(2 * n0) >= n0
    lofts = np.linalg.norm(Va[outer_idx] - Va[inner_idx], axis=1)
    log(f"{name}: shell built, loft mm mean {1000 * lofts.mean():.1f} min {1000 * lofts.min():.1f} "
        f"max {1000 * lofts.max():.1f}")
    trim_all = trim[og]
    # the fleece turned out at collar, cuffs and front edges bunches into locks
    dirn = N
    bumps = CT.fleece_bumps(V, SEED + 5)
    Va[outer_idx] += dirn * (0.0055 * trim * bumps - 0.0012 * trim)[:, None]
    set_verts(obj, Va)
    fields_all = {k: (d[og], a[og]) for k, (d, a) in fields.items()}
    shellc = is_outer.astype(np.float64)
    seams = seams0 | {(a + n0, b + n0) for a, b in seams0}
    uvpm, face_shell = CT.unwrap_coat(obj, is_outer, extra_seams=seams)
    tdir = gdir(name) / "Textures"
    tdir.mkdir(parents=True, exist_ok=True)
    cached = WORK / f"tex_{short}.json"
    if REUSE["tex"] and cached.exists():
        prev = json.loads(cached.read_text())
        paths = {k: Path(v) for k, v in prev["paths"].items()}
        stats = prev["stats"]
        log(f"{name}: reusing textures")
    else:
        paths, stats = CT.compose_coat(obj, fields_all, trim_all, shellc, face_shell, uvpm, tdir, short, R=4096,
                                       seed=SEED, log=log)
        cached.write_text(json.dumps(dict(paths={k: str(v) for k, v in paths.items()}, stats=stats)))
    mat = make_material("M_" + short, paths)
    obj.data.materials.clear()
    obj.data.materials.append(mat)
    parts = WR.toggles(obj, g.extra["opening"], V)
    join_parts(obj, parts, src)
    g.extra["edge_final"] = read_group(obj, "_edge", 0.05)
    attach(obj, arm)
    g.extra["inner_idx"] = inner_idx
    g.extra["loft_inner"] = lofts
    me = obj.data
    me.calc_loop_triangles()
    loft = dict(loft_mm_mean=round(1000 * float(lofts.mean()), 1), loft_mm_body=round(1000 * float(lofts[trim < 0.1].mean()), 1),
                loft_mm_trims=round(1000 * float(lofts[trim > 0.9].mean()), 1) if (trim > 0.9).any() else None,
                air_gap_to_skin_mm_median=round(1000 * float(np.median(gap)), 1))
    info = dict(vertices=len(me.vertices), triangles=len(me.loop_triangles), bones_weighted=len(obj.vertex_groups),
                accessories=len(parts), texel_uv_per_m=uvpm, textures={k: Path(v).name for k, v in paths.items()},
                texture_stats=stats, loft=loft)
    log(f"{name}: built {info['vertices']} verts, {info['triangles']} tris, loft {loft}")
    return info


