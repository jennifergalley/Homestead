def smooth_edges(V, F, loops, fixed, cons, hem_axis=None, iters=8):
    """Iron the open edges: smooth each boundary polyline, put it back outside the body and the
    layers below, then let the panel settle round the pinned edge."""
    V = V.copy()
    for lp in loops:
        P = V[lp]
        for _ in range(iters):
            P = P + 0.5 * (0.5 * (np.roll(P, 1, 0) + np.roll(P, -1, 0)) - P)
        V[lp] = P
    V = Ly.collide_layers(V, cons, rounds=2)
    V, _ = Ly.relax_layers(V, F, fixed, cons, hem_axis=hem_axis, iters=25, pinned=fixed)
    return V


def fit_trousers(body, layers):
    p = Tr.trousers_params(body)
    p.update(FITTED["trousers"])
    g = Tr.build_trousers(body, p)
    V, F = g.arrays()
    F = orient_out(V, F, body.all)
    loops = boundary_loops(F, len(V))
    fixed = np.zeros(len(V), bool)
    for lp in loops:
        fixed[lp] = True
    lab = Tr.trouser_labels(g, V)
    off = Tr.trouser_offsets(g, V, body)
    cons = [(Labelled([body.torso, body.leg_l, body.leg_r], lab), off, None),
            (Tr.LegDrape(body, p, "l", k=LEG_DRAPE_K), np.zeros(len(V)), lab == 1),
            (Tr.LegDrape(body, p, "r", k=LEG_DRAPE_K), np.zeros(len(V)), lab == 2),
            (Tr.Plane(1.0, 0.0022), np.zeros(len(V)), lab == 1),
            (Tr.Plane(-1.0, 0.0022), np.zeros(len(V)), lab == 2)]
    V, gaps = Ly.relax_layers(V, F, fixed, cons, iters=170, log=log)
    V = smooth_edges(V, F, loops, fixed, cons)
    gaps = [cons[0][0].signed(V)[0]]
    g.extra.update(labels=lab, loops=loops, gap=gaps[0], offsets=off, constraints=cons)
    log(f"{g.name}: {len(V)} verts, {len(F)} quads, loops {[len(l) for l in loops]}, "
        f"gap mm min {1000 * gaps[0].min():.2f} median {1000 * np.median(gaps[0]):.2f}")
    return g, V, F


def top_offsets(g, V, body, prof):
    p = g.extra["params"]
    reg = g.extra["region"]
    off = np.full(len(V), p["base"])
    sl = (reg == 1) | (reg == 2)
    off[sl] = p["sleeve_ease"]
    if p.get("cuff"):
        s = g.extra["axial"]
        for side in ("l", "r"):
            m = reg == (1 if side == "l" else 2)
            s_end = g.extra["sleeves"][side]["s_end"]
            u = np.clip((s_end - p["cuff"] - s[m]) / 0.05, 0, 1)
            off[m] = p["cuff_ease"] + (p["sleeve_ease"] - p["cuff_ease"]) * u
    if (reg == 3).any():
        off[reg == 3] = p["collar"]["off"]
    return off


def fit_top(body, kind, belt, layers, prof):
    p = Tp.top_params(body, kind, belt)
    p.update(FITTED[kind])
    g = Tp.build_top(body, p)
    V, F = g.arrays()
    F = orient_out(V, F, body.all)
    loops = boundary_loops(F, len(V))
    fixed = np.zeros(len(V), bool)
    for lp in loops:
        fixed[lp] = True
    off = top_offsets(g, V, body, prof)
    cons = [(Ly.ClosedSurface(body.all), off, None),
            (Ly.Drape(prof, p["hang"], p["ua_z"] + 0.03, p["base"]), np.zeros(len(V)), g.extra["region"] == 0)]
    low = V[:, 2] < 1.16
    for lay, loff in layers:
        cons.append((lay, np.full(len(V), loff), low if kind != "coat" else None))
    V, gaps = Ly.relax_layers(V, F, fixed, cons, hem_axis=g.extra["hem_axis"],
                              iters=200 if kind == "coat" else 170, log=log)
    V = smooth_edges(V, F, loops, fixed, cons, hem_axis=g.extra["hem_axis"])
    gaps = [body.all.signed(V)[0]]
    g.extra.update(loops=loops, gap=gaps[0], offsets=off, constraints=cons)
    log(f"{g.name}: {len(V)} verts, {len(F)} quads, loops {[len(l) for l in loops]}, "
        f"body gap mm min {1000 * gaps[0].min():.2f} median {1000 * np.median(gaps[0]):.2f}")
    # openings
    for key in ("slit", "opening"):
        if not p.get(key):
            continue
        n0 = len(V)
        if key == "slit":
            top = V[Tp.front_column(g)[-1], 2]
            z0 = top - p["slit"]
            V, F, le, ri = Tp.split_front(g, V, F, z0)
            V = Tp.spread_opening(V, le, ri, lambda v: 0.5 * p["slit_open"] * np.clip((v[2] - z0) / p["slit"], 0, 1) ** 1.3)
        else:
            V, F, le, ri = Tp.split_front(g, V, F, -1.0)
            V = Tp.spread_opening(V, le, ri, lambda v: p["open_gap"])
        g.extra[key] = (le, ri)
        src = np.concatenate([np.arange(n0), np.array(le, np.int64)])
        for k in ("region", "axial", "hem_axis", "gap", "offsets"):
            g.extra[k] = g.extra[k][src]
        g.extra["constraints"] = [(s, np.asarray(o)[src], None if m is None else m[src]) for s, o, m in cons]
        g.extra["src_map"] = src
    g.extra["loops"] = boundary_loops(F, len(V))
    return g, V, F


def garment_object(g, V, F, body):
    F = orient_out(V, F, body.all)
    me = bpy.data.meshes.new(g.name)
    me.from_pydata(V.tolist(), [], F.tolist())
    me.update()
    me.shade_smooth()
    panel = me.attributes.new("panel", "INT", "FACE")
    panel.data.foreach_set("value", np.array(g.face_panel, np.int32))
    for e in me.edges:
        a, b = sorted(e.vertices)
        e.use_seam = (a, b) in g.uv_seams
    return link(bpy.data.objects.new(g.name, me)), F


def fit_all(body, belt, shorts_obj, want=None):
    prof = Ly.RadialProfile(body, 0.98, 1.36)
    shorts_layer = mesh_layer(shorts_obj, body.all)
    out = {}
    g, V, F = fit_trousers(body, [])
    out[g.name] = (g, V, F)
    tr_layer = shell_layer(V, F, THICKNESS[g.name][0], g.name)
    shirt_layers = [(shorts_layer, 0.0030), (tr_layer, 0.0030)]
    for kind in ("tee", "longshirt"):
        if want and kind not in want and "coat" not in want:
            continue
        g, V, F = fit_top(body, kind, belt, shirt_layers, prof)
        out[g.name] = (g, V, F)
    if want and "coat" not in want:
        return out
    coat_layers = [(shorts_layer, 0.0035), (tr_layer, 0.0035)]
    for name in ("SKM_LinenTee", "SKM_LinenLongShirt"):
        gg, VV, FF = out[name]
        coat_layers.append((shell_layer(VV, FF, THICKNESS[name][0], name), 0.0040))
    g, V, F = fit_top(body, "coat", belt, coat_layers, prof)
    out[g.name] = (g, V, F)
    return out


