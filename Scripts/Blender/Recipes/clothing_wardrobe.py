def test_poses(arm, body, body_obj, garments, base, fitted):
    face_V = body.V[body.n_body:]
    face_N = body.N[body.n_body:]
    face_T = body.T[(body.T >= body.n_body).all(1)] - body.n_body
    rest_z = {n: np.array([v.co.z for v in o.data.vertices]) for n, o in garments.items()}
    metrics = {}
    for pose in WR.POSES:
        WR.apply_pose(arm, pose)
        surf = WR.posed_surface(arm, body_obj, face_V, face_N, face_T)
        m = {}
        for n, o in garments.items():
            m[n] = R.poke_metrics(o, surf, fitted[n][0].extra["edge_final"])
        lay = {}
        for top in ("SKM_LinenTee", "SKM_LinenLongShirt"):
            for under in ("SKM_PrimitiveShorts", "SKM_WoolTrousers"):
                inner = base.get(under) or garments.get(under)
                lay[f"{top} over {under}"] = WR.layer_poke(garments[top], inner, surf, mask=rest_z[top] < 1.16)
        coat = garments["SKM_FurCoat"]
        gc = fitted["SKM_FurCoat"][0]
        for top in ("SKM_LinenTee", "SKM_LinenLongShirt"):
            lay[f"SKM_FurCoat over {top}"] = WR.layer_poke(coat, garments[top], surf, idx=gc.extra["inner_idx"],
                                                           loft=gc.extra["loft_inner"])
        m["layers"] = lay
        metrics[pose] = m
        log(f"pose {pose}: " + ", ".join(f"{k.replace('SKM_', '')} {v['inside_pct']:.2f}% (max {v['max_depth_mm']:.1f} mm)"
                                         for k, v in m.items() if k != "layers"))
        log("   layers: " + ", ".join(f"{k.replace('SKM_', '')} {v['inside_pct']:.2f}%"
                                      + (f" / through {v['through_outer_pct']:.2f}%" if "through_outer_pct" in v else "")
                                      for k, v in lay.items()))
    R.reset_pose(arm)
    return metrics


