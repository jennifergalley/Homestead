def pouch_clearance(trousers):
    """How close the trousers come to the forage pouch where it lies on her right hip (the pouch
    was fitted over the shorts)."""
    try:
        fit = json.loads(POUCH_FIT.read_text())
        before = set(bpy.data.objects)
        bpy.ops.import_scene.fbx(filepath=str(POUCH_FBX))
        new = [o for o in bpy.data.objects if o not in before]
        mesh = next(o for o in new if o.type == "MESH")
        F0 = 0.040
        pivot = np.array(min(fit["belt"], key=lambda q: abs(-q[1] - F0)))
        V0, N, T = B.mesh_arrays(mesh)
        # the prop's own frame: pick the axis convention that puts it on her right hip
        best = None
        for sx, sy in ((1, 1), (1, -1), (-1, -1), (-1, 1)):
            V = V0 * np.array([sx, sy, 1.0]) + pivot
            err = np.linalg.norm(V.mean(0) - np.array([-0.17, -0.03, 0.89]))
            if best is None or err < best[0]:
                best = (err, V, (sx, sy))
        err, V, flip = best
        tV, tN, tT = B.mesh_arrays(trousers)
        ts = B.Surface(tV, tN, tT)
        s, _, _ = ts.signed(V)
        for o in new:
            bpy.data.objects.remove(o)
        return dict(pouch_vertices_inside_trousers=int((s < 0).sum()), min_signed_mm=round(1000 * float(s.min()), 2),
                    placement_error_m=round(float(err), 3), axis_flip=flip,
                    note="pouch placed at its belt pivot; positive = clear of the trousers' outer surface")
    except Exception as exc:  # the pouch is optional context
        return dict(error=str(exc))


def belt_clearance(done, fitted):
    belt = Tp.Belt(json.loads(BELT_JSON.read_text()))
    out = {}
    for name in ("SKM_LinenTee", "SKM_LinenLongShirt", "SKM_FurCoat"):
        o = done[name]
        n_shell = fitted[name][0].extra.get("n_shell") or 2 * len(fitted[name][0].extra["inner_idx"])
        V = np.array([v.co for v in o.data.vertices])[:n_shell]
        lo = []
        for t in range(-180, 180, 10):
            tr = math.radians(t)
            d = np.array([math.sin(tr), -math.cos(tr)])
            sel = ((V[:, :2] @ d) > 0.97 * np.linalg.norm(V[:, :2], axis=1)) & (np.abs(V[:, 0]) < 0.19) & (V[:, 2] < 1.3)
            if sel.any():
                lo.append(float(V[sel, 2].min() - (belt.z(t) + belt.radius)))
        out[name] = dict(min_hem_above_belt_top_mm=round(1000 * min(lo), 1) if lo else None)
    return out


def sha256(path):
    import hashlib
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


