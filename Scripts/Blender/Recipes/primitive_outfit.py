def log(msg):
    print(f"[outfit {time.time() - T0:7.1f}s] {msg}", flush=True)


def link(obj, coll=None):
    (coll or bpy.context.scene.collection).objects.link(obj)
    return obj


def garment_object(g, V, F, body):
    """Create the Blender mesh for a fitted garment with outward-facing quads."""
    import bmesh
    me = bpy.data.meshes.new(g.name)
    me.from_pydata(V.tolist(), [], F.tolist())
    me.update()
    bm = bmesh.new()
    bm.from_mesh(me)
    bm.faces.ensure_lookup_table()
    cent = np.array([f.calc_center_median() for f in bm.faces])
    nrm = np.array([f.normal for f in bm.faces])
    _, loc, bn = body.all.signed(cent)
    flip = [bm.faces[i] for i in np.where((nrm * bn).sum(1) < 0)[0]]
    if flip:
        bmesh.ops.reverse_faces(bm, faces=flip)
    bm.to_mesh(me)
    bm.free()
    me.shade_smooth()
    panel = me.attributes.new("panel", "INT", "FACE")
    panel.data.foreach_set("value", np.array(g.face_panel, np.int32))
    for e in me.edges:
        a, b = sorted(e.vertices)
        e.use_seam = (a, b) in g.uv_seams
    obj = link(bpy.data.objects.new(g.name, me))
    return obj


def fit(body):
    out = {}
    for build in (G.build_tank_top, G.build_shorts):
        g = build(body)
        V, F = g.arrays()
        loops = G.boundary_loops(F, len(V))
        fixed = np.zeros(len(V), bool)
        for lp in loops:
            fixed[lp] = True
        log(f"{g.name}: {len(V)} verts, {len(F)} quads, {len(loops)} boundary loops {[len(l) for l in loops]}")
        surfs, labels = G.surface_labels(g, V, body)
        V, gap = G.relax(V, F, fixed, G.MultiSurface(surfs, labels), G.offsets(g, V, body), log=log)
        g.extra["labels"] = labels
        for lp in loops:
            P = V[lp]
            d = np.linalg.norm(np.diff(np.vstack([P, P[:1]]), axis=0), axis=1)
            log(f"  boundary loop {len(lp)}: z {P[:, 2].min():.3f}-{P[:, 2].max():.3f}, longest edge {1000 * d.max():.1f} mm")
        g.extra["gap"] = gap
        g.extra["loops"] = loops
        out[g.name] = (g, V, F)
    return out


def preview(objs, body_obj, path, views=(("front", (0, -4, 1.1), (90, 0, 0)),
                                         ("side", (4, 0, 1.1), (90, 0, 90)),
                                         ("back", (0, 4, 1.1), (90, 0, 180)))):
    import math
    sc = bpy.context.scene
    sc.render.engine = "BLENDER_WORKBENCH"
    sc.display.shading.light = "STUDIO"
    sc.display.shading.color_type = "OBJECT"
    sc.render.resolution_x, sc.render.resolution_y = 900, 1100
    for o in bpy.context.scene.objects:
        if o.type == "MESH" and o not in objs:
            o.color = (0.75, 0.55, 0.45, 1)
    for o in objs:
        o.color = (0.9, 0.9, 0.85, 1) if "Tank" in o.name else (0.7, 0.6, 0.45, 1)
    cam = bpy.data.objects.get("PreviewCam") or link(bpy.data.objects.new("PreviewCam", bpy.data.cameras.new("PreviewCam")))
    cam.data.type = "ORTHO"
    cam.data.ortho_scale = 0.95
    sc.camera = cam
    for name, loc, rot in views:
        cam.location = loc
        cam.rotation_euler = [math.radians(a) for a in rot]
        sc.render.filepath = str(path).replace(".png", f"_{name}.png")
        bpy.ops.render.render(write_still=True)


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", default="all", choices=["build", "render", "all", "fit", "tex"])
    ap.add_argument("--samples", type=int, default=192)
    ap.add_argument("--reuse-textures", action="store_true", help="skip texture synthesis if cached (iteration)")
    ap.add_argument("--only", nargs="*", help="render only these view names")
    args = ap.parse_args(argv)
    global REUSE_TEX
    REUSE_TEX = args.reuse_textures
    if args.stage == "render":
        render_stage(args)
        return
    np.random.seed(SEED)
    WORK.mkdir(parents=True, exist_ok=True)
    bpy.ops.wm.read_factory_settings(use_empty=True)
    arm, meshes = B.import_skeletal(BODY_FBX)
    arm.name = "root"
    body_obj = meshes[0]
    body_obj.name = "SKM_MHC_Heroine_BodyMesh"
    face_arm, face_meshes = B.import_skeletal(FACE_FBX)
    face_arm.name = "FaceRig"
    face_obj = face_meshes[0]
    face_obj.name = "SKM_MHC_Heroine_FaceMesh"
    log(f"face mesh: {len(face_obj.data.vertices)} verts, materials {[m.name for m in face_obj.data.materials if m]}")
    body = B.Body(arm, body_obj, extra=[face_obj])
    log("landmarks " + json.dumps({k: (np.round(v, 4).tolist() if isinstance(v, list) else round(v, 4))
                                  for k, v in body.lm.items()}))
    fitted = fit(body)
    objs = []
    for name, (g, V, F) in fitted.items():
        obj = garment_object(g, V, F, body)
        objs.append(obj)
        log(f"{name}: gap mm min {1000 * g.extra['gap'].min():.2f} median {1000 * np.median(g.extra['gap']):.2f}"
            f" max {1000 * g.extra['gap'].max():.2f}")
    if args.stage == "fit":
        preview(objs, body_obj, WORK / "fit.png")
        bpy.ops.wm.save_as_mainfile(filepath=str(WORK / "fit.blend"))
        return
    finish_build(args, arm, body, body_obj, face_obj, fitted, objs)
    if args.stage == "all":
        render_stage(args)


