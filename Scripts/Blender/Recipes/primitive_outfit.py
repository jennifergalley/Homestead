def render_stage(args):
    bpy.ops.wm.open_mainfile(filepath=str(BLEND))
    RENDERS.mkdir(parents=True, exist_ok=True)
    backend = Rn.setup_scene(HDRI, args.samples)
    log(f"render device {backend}")
    arm = bpy.data.objects["root"]
    body_obj = bpy.data.objects["SKM_MHC_Heroine_BodyMesh"]
    garments = [bpy.data.objects[n] for n in ("SKM_PrimitiveTankTop", "SKM_PrimitiveShorts")]
    face = bpy.data.objects["SKM_MHC_Heroine_FaceMesh"]
    want = set(args.only or [])
    done = []
    R.reset_pose(arm)
    for name, (tgt, d, dist, lens, res, fstop) in BEAUTY_VIEWS.items():
        if want and name not in want:
            continue
        done.append(Rn.shoot(RENDERS / f"beauty_{name}.png", tgt, d, dist, lens, res, fstop))
        log(f"rendered {name}")
    for pose in R.POSES:
        if want and pose not in want:
            continue
        R.apply_pose(arm, pose)
        R.ground(arm, [body_obj, face] + garments)
        V = np.vstack([B.mesh_arrays(o)[0] for o in [body_obj, face]])
        lo, hi = V.min(0), V.max(0)
        c = (lo + hi) / 2
        size = float(np.max(hi - lo))
        done.append(Rn.shoot(RENDERS / f"pose_{pose}.png", tuple(c), (-0.8, -1, 0.18), 1.55 * size + 1.2, 55,
                             (2160, 3840), None))
        log(f"rendered pose {pose}")
    R.reset_pose(arm)
    return done


def make_material(name, paths):
    mat = bpy.data.materials.new(name)
    if mat.node_tree is None:
        mat.use_nodes = True
    nt = mat.node_tree
    bsdf = nt.nodes["Principled BSDF"]

    def tex(path, srgb):
        node = nt.nodes.new("ShaderNodeTexImage")
        node.image = bpy.data.images.load(str(path), check_existing=True)
        node.image.colorspace_settings.name = "sRGB" if srgb else "Non-Color"
        return node

    base, ao = tex(paths["basecolor"], True), tex(paths["ao"], False)
    mix = nt.nodes.new("ShaderNodeMix")
    mix.data_type = "RGBA"
    mix.blend_type = "MULTIPLY"
    mix.inputs["Factor"].default_value = 0.6
    nt.links.new(base.outputs["Color"], mix.inputs["A"])
    nt.links.new(ao.outputs["Color"], mix.inputs["B"])
    nt.links.new(mix.outputs["Result"], bsdf.inputs["Base Color"])
    rough = tex(paths["roughness"], False)
    nt.links.new(rough.outputs["Color"], bsdf.inputs["Roughness"])
    nrm = tex(paths["normal"], False)
    nmap = nt.nodes.new("ShaderNodeNormalMap")
    nt.links.new(nrm.outputs["Color"], nmap.inputs["Color"])
    nt.links.new(nmap.outputs["Normal"], bsdf.inputs["Normal"])
    bsdf.inputs["Specular IOR Level"].default_value = 0.35
    bsdf.inputs["Sheen Weight"].default_value = 0.0
    return mat


def detail_and_texture(body, fitted, objs):
    TEX.mkdir(parents=True, exist_ok=True)
    info = {}
    for obj in objs:
        g, V, F = fitted[obj.name]
        surfs, labels = G.surface_labels(g, V, body)
        surf = G.MultiSurface(surfs, labels)
        off = G.offsets(g, V, body)
        fields = D.feature_fields(g, V, g.extra["loops"])
        h = D.wrinkles(g, V, fields, body, SEED)
        _, _, nrm = surf.signed(V)
        V2, gap = D.collide(V + nrm * h[:, None], surf, off)
        for i, v in enumerate(obj.data.vertices):
            v.co = V2[i]
        obj.data.update()
        fitted[obj.name] = (g, V2, F)
        g.extra["gap"] = gap
        g.extra["fields"] = fields
        uvpm = D.unwrap(obj)
        short = obj.name.replace("SKM_", "")
        cached = WORK / "tex_info.json"
        if REUSE_TEX and cached.exists() and obj.name in json.loads(cached.read_text()):
            prev = json.loads(cached.read_text())[obj.name]
            paths = {k: TEX / v for k, v in prev["textures"].items()}
            stats = {k: v for k, v in prev.items() if k not in ("textures", "texel_uv_per_m")}
            log(f"{obj.name}: reusing cached textures")
        else:
            paths, stats = C.compose(obj, fields, uvpm, TEX, short, R=TEX_SIZE, seed=SEED, log=log)
        mat = make_material("M_" + short, paths)
        obj.data.materials.clear()
        obj.data.materials.append(mat)
        info[obj.name] = dict(texel_uv_per_m=uvpm, textures={k: p.name for k, p in paths.items()}, **stats)
        log(f"{obj.name}: textures {stats}")
    info["detail"] = {k: p.name for k, p in C.detail_weave(TEX, SEED).items()}
    return info


EDGE_FIELDS = {"SKM_PrimitiveTankTop": ("hem", "bind"), "SKM_PrimitiveShorts": ("waist", "leghem")}


def rig_garments(arm, body, body_obj, face_obj, fitted, objs):
    src = R.weight_source(body_obj, face_obj, arm)
    rng = np.random.default_rng(SEED)
    info = {}
    for obj in objs:
        g, V, F = fitted[obj.name]
        fields = g.extra["fields"]
        edge = np.min([fields[n][0] for n in EDGE_FIELDS[obj.name]], axis=0)
        R.transfer_weights(obj, src)
        names, W = R.read_weights(obj)
        gap = g.extra["gap"]
        alpha = np.clip((gap - 0.006) / 0.02, 0.05, 0.5)
        W = R.clean_weights(W, alpha, G.edges_of(F), iters=3)
        R.write_weights(obj, names, W)
        vg = obj.vertex_groups.new(name="_edge")
        for i, d in enumerate(edge):
            vg.add([i], float(np.clip(d / 0.05, 0, 1)), "REPLACE")
        thick = 1 - D._smooth(edge, 0.004, 0.011)
        R.solidify(obj, thick)
        parts = R.accessories(obj, fields, V, rng, drawstring="Shorts" in obj.name)
        for p in parts:
            R.transfer_weights(p, src)
            pn, pw = R.read_weights(p)
            R.write_weights(p, pn, R.clean_weights(pw))
            p.data.materials.append(obj.data.materials[0])
        bpy.ops.object.select_all(action="DESELECT")
        for p in parts:
            p.select_set(True)
        obj.select_set(True)
        bpy.context.view_layer.objects.active = obj
        bpy.ops.object.join()
        eg = obj.vertex_groups["_edge"]
        e = np.zeros(len(obj.data.vertices))
        for v in obj.data.vertices:
            for gg in v.groups:
                if gg.group == eg.index:
                    e[v.index] = gg.weight * 0.05
        obj.vertex_groups.remove(eg)
        g.extra["edge_final"] = e
        mod = obj.modifiers.new("Armature", "ARMATURE")
        mod.object = arm
        obj.parent = arm
        names = [vg.name for vg in obj.vertex_groups]
        me = obj.data
        me.calc_loop_triangles()
        info[obj.name] = dict(vertices=len(me.vertices), triangles=len(me.loop_triangles),
                              bones_weighted=len(names), accessories=len(parts))
        log(f"{obj.name}: rigged, {len(me.vertices)} verts, {len(me.loop_triangles)} tris, {len(names)} weighted bones")
    bpy.data.objects.remove(src)
    return info


def test_poses(arm, body, body_obj, objs, fitted):
    metrics = {}
    face_V = body.V[body.n_body:]
    face_N = body.N[body.n_body:]
    face_T = body.T[(body.T >= body.n_body).all(1)] - body.n_body
    for pose in R.POSES:
        R.apply_pose(arm, pose)
        V, N, Tr = B.mesh_arrays(body_obj)
        hb = arm.pose.bones["head"]
        M = np.array(arm.matrix_world @ hb.matrix @ hb.bone.matrix_local.inverted())
        fV = face_V @ M[:3, :3].T + M[:3, 3]
        fN = face_N @ M[:3, :3].T
        surf = B.Surface(np.vstack([V, fV]), np.vstack([N, fN]), np.vstack([Tr, face_T + len(V)]))
        metrics[pose] = {o.name: R.poke_metrics(o, surf, fitted[o.name][0].extra["edge_final"]) for o in objs}
        log(f"pose {pose}: " + ", ".join(f"{k}: {v['inside_pct']:.2f}% inside ({v['inside_near_edge']} near edges),"
                                         f" max {v['max_depth_mm']:.1f} mm" for k, v in metrics[pose].items()))
    R.reset_pose(arm)
    return metrics


def finish_build(args, arm, body, body_obj, face_obj, fitted, objs):
    tex_info = detail_and_texture(body, fitted, objs)
    (WORK / "tex_info.json").write_text(json.dumps(tex_info, indent=1, default=str))
    if args.stage == "tex":
        bpy.ops.wm.save_as_mainfile(filepath=str(WORK / "textured.blend"))
        return
    rig_info = rig_garments(arm, body, body_obj, face_obj, fitted, objs)
    bind = {}
    for o in objs:
        bind[o.name] = R.poke_metrics(o, body.all, fitted[o.name][0].extra["edge_final"])
    log(f"bind pose: {bind}")
    pose_metrics = test_poses(arm, body, body_obj, objs, fitted)
    exports = {}
    for o in objs:
        n, bones = R.export_fbx(OUT / f"{o.name}.fbx", arm, [o], log=log)
        exports[o.name] = dict(file=f"{o.name}.fbx", bones=n, bone_names=bones)
    combo = [o.copy() for o in objs]
    for c, o in zip(combo, objs):
        c.data = o.data.copy()
        link(c)
    bpy.ops.object.select_all(action="DESELECT")
    for c in combo:
        c.select_set(True)
    bpy.context.view_layer.objects.active = combo[0]
    bpy.ops.object.join()
    outfit = bpy.context.view_layer.objects.active
    outfit.name = outfit.data.name = "SKM_PrimitiveOutfit"
    n, bones = R.export_fbx(OUT / "SKM_PrimitiveOutfit.fbx", arm, [outfit], log=log)
    exports["SKM_PrimitiveOutfit"] = dict(file="SKM_PrimitiveOutfit.fbx", bones=n, bone_names=bones)
    bpy.data.objects.remove(outfit)
    cov_info, _ = R.coverage_mask(body_obj, objs, {o.name: fitted[o.name][0].extra["edge_final"] for o in objs},
                                  OUT / "BodyCoverageMask.png")
    log(f"coverage: {cov_info}")
    report = dict(recipe="Scripts/Blender/Recipes/primitive_outfit.py", seed=SEED, blender=bpy.app.version_string,
                  inputs={p.name: sha256(p) for p in (BODY_FBX, FACE_FBX)}, landmarks=body.lm,
                  params={o.name: fitted[o.name][0].extra["params"] for o in objs},
                  garments=rig_info, textures=tex_info, bind_pose=bind, test_poses=pose_metrics,
                  exports=exports, coverage=cov_info,
                  export_settings=dict(units="centimeters (FBX UnitScaleFactor 1.0, raw cm values like the UE export)",
                                       axes="Z up, -Y forward (FBX UpAxis Z, FrontAxis -Y), same as input",
                                       armature="object 'root' exported as the root bone above pelvis",
                                       leaf_bones=False, animation=False, deform_only=True,
                                       smoothing="FACE", tangents=True))
    report["files"] = {p.name: sha256(p) for p in sorted(OUT.glob("*.fbx"))}
    report["files"].update({f"Textures/{p.name}": sha256(p) for p in sorted(TEX.glob("*.png"))})
    report["files"]["BodyCoverageMask.png"] = sha256(OUT / "BodyCoverageMask.png")
    (OUT / "report.json").write_text(json.dumps(report, indent=1, default=float) + "\n")
    Rn.prepare_face(face_obj, bpy.data.objects["FaceRig"], arm)
    Rn.assign_review_materials(body_obj, face_obj)
    for o in list(bpy.data.objects):
        if o.name == "PreviewCam":
            bpy.data.objects.remove(o)
    bpy.ops.wm.save_as_mainfile(filepath=str(BLEND), relative_remap=True)
    log(f"saved {BLEND}")


def sha256(path):
    import hashlib
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


if __name__ == "__main__":
    main()
