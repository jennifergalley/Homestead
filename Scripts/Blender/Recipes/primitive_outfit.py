"""Homestead: makeshift homespun outfit for the MetaHuman heroine (cropped tank top + low-rise shorts).

Reproducible, seeded Blender 5.2 build. Run headless from the repo root:

    & "C:\\Program Files\\Blender Foundation\\Blender 5.2\\blender.exe" --background --factory-startup `
        --python Scripts\\Blender\\Recipes\\primitive_outfit.py -- --stage all

Stages: ``build`` (fit, detail, UVs, textures, weights, export, coverage mask, .blend),
``render`` (4K Cycles beauty + test-pose renders from the saved .blend), ``all`` (both).
``--preview`` writes quick Workbench fit previews instead of the Cycles renders.

Inputs (exported from Unreal, outside the repo): the heroine's un-culled MetaHuman body
``SKM_MHC_Heroine_BodyMesh_Full.fbx`` and face ``SKM_MHC_Heroine_FaceMesh.fbx`` on
``metahuman_base_skel`` (cm, Z up, -Y forward). Outputs go to Assets/Characters/PrimitiveOutfit.

Garment research notes (what we are imitating): pre-industrial homespun linen/hemp or cotton
is a plain (tabby) weave of hand-spun yarn, roughly 8-12 threads/cm, with slubs (thick, soft
spots) and uneven thread spacing; undyed linen is a grey-cream to oatmeal colour that yellows
and greys with wear. Garments are sewn from flat pattern pieces with running or back stitches
(~3-4 stitches/cm by hand), seams pressed to one side, and edges finished by a narrow rolled or
double-turned hem, bias binding, or a folded casing for a drawstring. Woven cloth barely
stretches, so it tents over the bust apex and bridges hollows instead of clinging like knit,
creases sharply and gathers where a drawstring cinches it.

PROVENANCE: all garment geometry and textures are original and generated by this script
(numpy procedural weave/stain/seam maps). Review renders use the CC0 Poly Haven HDRI
"Kloofendal 48d Partly Cloudy (Pure Sky)" (render lighting only, not shipped with the asset).
"""
