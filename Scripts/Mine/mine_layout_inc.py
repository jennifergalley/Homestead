"""Write Source/SurvivalGame/Simulation/HomesteadMineLayout.inc from Scripts/Blender/Recipes/mine/layout.py.

    python Scripts\\Mine\\mine_layout_inc.py

The interface between Mine Art (the house, the shallow level and where its nodes sit) and Mine
Gameplay (HomesteadMine.cpp defines the macros). World centimetres; yaw in degrees from +X toward +Y.
Placement ids 588000-588099 belong to the mine's art (round-4.md).
"""
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "Scripts" / "Blender" / "Recipes"))
from mine import layout as L  # noqa: E402

OUT = ROOT / "Source" / "SurvivalGame" / "Simulation" / "HomesteadMineLayout.inc"
CM = 100.0
WAKE_POINT = (0.6, -1.5)         # house frame: inside the door, clear of the desk, crates and trapdoor
LADDER_TOP_GAP = 0.40            # she stands this far west of the opening's west edge (the ladder's side)
LADDER_FOOT = (1.1, 0.0)         # tunnel frame: a pace east of the ladder, facing down the adit
SUMP_CLEAR = 1.3                 # the alcove's walkable floor stops this short of the sump's centre


def c(v):
    return f"{v * CM:.1f}"


def house(x, y, z=0.0):
    return L.house_to_world(x, y, z)


def tunnel(x, y, z=0.0):
    return L.tunnel_to_world(x, y, z)


def yaw(deg):
    return f"{(deg + L.HOUSE_YAW + 180.0) % 360.0 - 180.0:.2f}"


def lines():
    out = ["// Generated by Scripts/Mine/mine_layout_inc.py from Scripts/Blender/Recipes/mine/layout.py; do not",
           "// edit by hand. World centimetres; yaw in degrees from +X toward +Y. Ids 588000-588099 (round-4.md):",
           f"// {L.ROCK_PILE_ID} the rock pile, {L.TRAPDOOR_ID} the trapdoor, {L.LADDER_FOOT_ID} the ladder foot, "
           "588010-588029 rock faces, 588030-588035 coal,",
           "// 588040-588043 copper, 588050-588052 gem pockets. Node kind: 0 rock face, 1 coal seam, 2 copper vein, 3 gem pocket."]
    hx, hy, hz = house(0.0, 0.0)
    out.append(f"MINE_HOUSE({c(hx)}, {c(hy)}, {c(hz)}, {yaw(0.0)})")
    out.append("// The doorway's threshold, on the outer face of the east gable.")
    out.append("MINE_DOOR({}, {}, {})".format(*map(c, house(L.OUT_X / 2, L.DOOR["centre"], L.FLOOR_Z))))
    out.append("// Ground-floor stand point: where she wakes after exhaustion underground (design D4).")
    out.append("MINE_HOUSE_FLOOR({}, {}, {})".format(*map(c, house(*WAKE_POINT, L.FLOOR_Z))))
    tx, ty = L.TRAPDOOR["centre"]
    sx, sy = L.TRAPDOOR["size"]
    out.append("// Trapdoor: hinge line centre (the +Y edge of the opening), yaw from the hinge toward the closed")
    out.append("// lid's free edge, lid length (hinge to free edge) x width (along the hinge).")
    lap = L.TRAPDOOR_LAP
    out.append("MINE_TRAPDOOR({}, {}, {}, {}, {}, {})".format(*map(c, house(tx, ty + sy / 2 + lap, L.FLOOR_Z)),
                                                           yaw(-90.0), c(sy + 2 * lap), c(sx + 2 * lap)))
    out.append("// Ladder top: on the ladder's side (-X, the desk side) of the opening, facing it (the ladder tops out")
    out.append("// just under the floor, under the lid; she turns and steps back onto it). Ladder foot: on the tunnel floor.")
    out.append("MINE_LADDER_TOP({}, {}, {}, {})".format(*map(c, house(tx - sx / 2 - LADDER_TOP_GAP, ty, L.FLOOR_Z)),
                                                        yaw(0.0)))
    out.append("MINE_LADDER_FOOT({}, {}, {}, {})".format(*map(c, tunnel(*LADDER_FOOT)), yaw(0.0)))
    out.append("// The rock pile's centre on the floor (a one-time 25 stone).")
    out.append("MINE_PILE({}, {}, {})".format(*map(c, house(*L.ROCK_PILE["centre"], L.FLOOR_Z))))
    lx, ly, lz = L.LAMP_ON_DESK
    out.append("// The desk lamp's flame (it burns forever and can't be taken).")
    out.append("MINE_DESK_LAMP({}, {}, {})".format(*map(c, house(lx, ly, lz + 0.20))))
    out.append("// The top of the shaft above the ladder chamber (daylight comes down it by day).")
    out.append("MINE_DAYLIGHT({}, {}, {})".format(*map(c, tunnel(*L.SHAFT["centre"], L.CHAMBER["height"] + L.SHAFT["height"]))))
    out.append("// Nodes: id, kind, ground point of the face, yaw it faces, unit normal into the gallery.")
    for nid, kind, (x, y), deg, (nx, ny) in L.node_sockets():
        wx, wy, wz = tunnel(x, y)
        r = math.radians(L.HOUSE_YAW)
        wnx, wny = nx * math.cos(r) - ny * math.sin(r), nx * math.sin(r) + ny * math.cos(r)
        out.append(f"MINE_NODE({nid}, {kind}, {c(wx)}, {c(wy)}, {c(wz)}, {yaw(deg)}, {wnx:.4f}, {wny:.4f})")
    out.append("// Walkable floor: centreline segments with their half widths (the ladder chamber first).")
    cx, cy = L.CHAMBER["centre"]
    chx, chy = L.CHAMBER["half"]
    a, b = tunnel(cx - chx + chy, cy), tunnel(cx + chx - chy, cy)
    out.append(f"MINE_FLOOR({c(a[0])}, {c(a[1])}, {c(b[0])}, {c(b[1])}, {c(chy - 0.4)}, {c(a[2])})")
    for f, t, kind in L.EDGES:
        pa, pb = L.POINTS[f], L.POINTS[t]
        half = L.edge_half((f, t)) - 0.35
        if kind == "alcove":
            sx_, sy_ = L.SUMP["centre"]
            d = math.dist(pa, (sx_, sy_))
            k = max(0.0, (d - SUMP_CLEAR) / d)
            pb = (pa[0] + (sx_ - pa[0]) * k, pa[1] + (sy_ - pa[1]) * k)
            half = 0.8
        a, b = tunnel(*pa), tunnel(*pb)
        out.append(f"MINE_FLOOR({c(a[0])}, {c(a[1])}, {c(b[0])}, {c(b[1])}, {c(half)}, {c(a[2])})")
    return out


def main():
    OUT.write_text("\r\n".join(lines()) + "\r\n", encoding="utf-8", newline="")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
